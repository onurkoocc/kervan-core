-- Kervan core schema (SPEC §5.1). Data classes (SPEC §5.2): customers.full_name, phone and
-- email are confidential; everything else here is internal.

create table customers (
    id        bigint generated by default as identity primary key,
    full_name text not null,
    phone     text not null,
    email     text,
    city      text
);

create table shipments (
    tracking_no      text primary key check (tracking_no ~ '^KRV[0-9]{8}$'),
    customer_id      bigint not null references customers (id),
    status           text not null check (status in ('CREATED', 'IN_TRANSIT', 'OUT_FOR_DELIVERY', 'DELIVERED', 'RETURNED')),
    origin_city      text not null,
    destination_city text not null,
    created_at       timestamptz not null default now()
);

create index shipments_customer_id on shipments (customer_id);

-- "window" is a reserved word in PostgreSQL: always quote it.
create table deliveries (
    id            bigint generated by default as identity primary key,
    tracking_no   text not null unique references shipments (tracking_no),
    delivery_date date not null,
    "window"      text not null check ("window" in ('MORNING', 'AFTERNOON', 'EVENING')),
    status        text not null check (status in ('SCHEDULED', 'RESCHEDULED', 'DELIVERED', 'FAILED')),
    attempts      int not null default 0 check (attempts >= 0)
);

-- The service inserts events and tickets; their ids start high so that seed rows with
-- small explicit ids never collide with them.
create table shipment_events (
    id          bigint generated by default as identity (start with 1000000) primary key,
    tracking_no text not null references shipments (tracking_no),
    at          timestamptz not null,
    description text not null
);

create index shipment_events_tracking_no_at on shipment_events (tracking_no, at desc);

create table tickets (
    id          bigint generated by default as identity (start with 1000000) primary key,
    ticket_id   text not null unique check (ticket_id ~ '^TCK-[0-9]{6}$'),
    tracking_no text null references shipments (tracking_no),
    category    text not null check (category in ('DAMAGED', 'LOST', 'DELAY', 'OTHER')),
    description text not null check (length(description) <= 2000),
    status      text not null default 'OPEN' check (status in ('OPEN', 'CLOSED')),
    channel     text not null check (channel in ('agent', 'web', 'phone')),
    created_at  timestamptz not null default now()
);

create index tickets_tracking_no on tickets (tracking_no);

-- New ticket numbers; TCK-000001 … TCK-100000 are left to seed data.
create sequence ticket_number_seq start with 100001 minvalue 1 maxvalue 999999 no cycle;
